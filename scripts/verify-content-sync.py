#!/usr/bin/env python3
"""
Principal Journey — Content Bundle & Curriculum Sync Gate (`verify-content-sync.py`)
Enforces:
  1. Every sprint/war-room/template `.md` file on disk is bundled in `content-db.js` (or rebuilds with `--rebuild`).
  2. SHA-256 content digest matches between disk `.md` files and `window.CONTENT_DB`.
  3. Zero numbering holes (`01`..`NN`) across all numbered sprint directories (`00`..`16`).
  4. Every `path` entry inside `dashboard.html` resolves to a real on-disk `.md` file.
"""

import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT_DB_PATH = os.path.join(ROOT, "content-db.js")
DASHBOARD_PATH = os.path.join(ROOT, "dashboard.html")

INCLUDED_DIRS = [
    "00-Foundation",
    "01-Production-Ready-WebAPI",
    "01-Production-Ready-WebAPI-WarRoom",
    "02-Authentication",
    "02-Authentication-WarRoom",
    "03-Storage",
    "03-Storage-WarRoom",
    "04-Database",
    "04-Database-WarRoom",
    "05-Concurrency",
    "05-Concurrency-WarRoom",
    "06-Messaging",
    "06-Messaging-WarRoom",
    "07-Distributed-Systems",
    "07-Distributed-Systems-WarRoom",
    "08-Cloud-Native",
    "08-Cloud-Native-WarRoom",
    "09-Observability",
    "09-Observability-WarRoom",
    "10-System-Design",
    "10-System-Design-WarRoom",
    "11-DevOps-And-Pipelines",
    "11-DevOps-And-Pipelines-WarRoom",
    "12-AI-And-Agents",
    "12-AI-And-Agents-WarRoom",
    "13-Frontend-Architecture",
    "13-Frontend-Architecture-WarRoom",
    "14-Principal-Review",
    "15-Zero-Downtime-Data-Evolution",
    "15-Zero-Downtime-Data-Evolution-WarRoom",
    "16-Multi-Region-And-Disaster-Recovery",
    "16-Multi-Region-And-Disaster-Recovery-WarRoom",
    "templates",
]

def collect_disk_markdown_files():
    db = {}
    for folder in INCLUDED_DIRS:
        folder_path = os.path.join(ROOT, folder)
        if not os.path.exists(folder_path):
            continue
        for root_dir, _, files in os.walk(folder_path):
            for fname in sorted(files):
                if fname.endswith(".md"):
                    abs_path = os.path.join(root_dir, fname)
                    rel_path = os.path.relpath(abs_path, ROOT).replace("\\", "/")
                    with open(abs_path, "r", encoding="utf-8") as f:
                        db[rel_path] = f.read()
    # Also include top-level ROADMAP.md and ENHANCEMENT_PLAN.md
    for top_md in ["ROADMAP.md", "ENHANCEMENT_PLAN.md"]:
        top_path = os.path.join(ROOT, top_md)
        if os.path.exists(top_path):
            with open(top_path, "r", encoding="utf-8") as f:
                db[top_md] = f.read()
    return db

def compute_manifest_sha256(db_dict):
    h = hashlib.sha256()
    for k in sorted(db_dict.keys()):
        h.update(k.encode("utf-8"))
        h.update(b"\0")
        h.update(db_dict[k].encode("utf-8"))
        h.update(b"\0")
    return h.hexdigest()

def check_contiguous_numbering():
    errors = []
    for folder in INCLUDED_DIRS:
        if folder == "templates":
            continue
        folder_path = os.path.join(ROOT, folder)
        if not os.path.exists(folder_path):
            errors.append(f"Missing directory: {folder}")
            continue
        nums = set()
        for f in os.listdir(folder_path):
            if f.endswith(".md") and f != "README.md":
                m = re.match(r"^(\d+)[A-Z]?-", f)
                if m:
                    nums.add(int(m.group(1)))
        if nums:
            expected = set(range(1, max(nums) + 1))
            missing = sorted(expected - nums)
            if missing:
                errors.append(f"Numbering hole in {folder}: missing {missing}")
    return errors

def rebuild_content_db(disk_db):
    digest = compute_manifest_sha256(disk_db)
    js_payload = (
        f"// AUTO-GENERATED BY scripts/verify-content-sync.py — DO NOT EDIT MANUALLY\n"
        f"// SHA256_MANIFEST: {digest}\n"
        f"// TOTAL_FILES: {len(disk_db)}\n"
        f"window.CONTENT_DB_MANIFEST_HASH = {json.dumps(digest)};\n"
        f"window.OFFLINE_CURRICULUM_DB = window.CONTENT_DB = {json.dumps(disk_db, ensure_ascii=False, indent=2)};\n"
    )
    with open(CONTENT_DB_PATH, "w", encoding="utf-8") as f:
        f.write(js_payload)
    print(f"[REBUILT] content-db.js ({len(disk_db)} files, {len(js_payload):,} bytes, hash={digest[:16]}...)")

def verify_sync(disk_db):
    errors = []
    expected_hash = compute_manifest_sha256(disk_db)

    if not os.path.exists(CONTENT_DB_PATH):
        errors.append("content-db.js does not exist!")
    else:
        head = open(CONTENT_DB_PATH, "r", encoding="utf-8").read(512)
        m = re.search(r"SHA256_MANIFEST:\s*([0-9a-f]{64})", head)
        if not m or m.group(1) != expected_hash:
            errors.append(f"content-db.js is STALE! Expected hash {expected_hash[:16]}..., found {m.group(1)[:16] if m else 'NONE'}.")

    # Verify numbering
    errors.extend(check_contiguous_numbering())

    # Verify dashboard.html paths
    if os.path.exists(DASHBOARD_PATH):
        dash = open(DASHBOARD_PATH, "r", encoding="utf-8").read()
        paths = re.findall(r'path:\s*["\']([^"\']+\.md)["\']', dash)
        for p in paths:
            if p not in disk_db and not os.path.exists(os.path.join(ROOT, p)):
                errors.append(f"Broken path in dashboard.html: {p}")

    return errors

if __name__ == "__main__":
    disk_db = collect_disk_markdown_files()
    if "--rebuild" in sys.argv:
        rebuild_content_db(disk_db)

    errs = verify_sync(disk_db)
    if errs:
        print("CI SYNC GATE FAILED:")
        for e in errs:
            print(f"  [X] {e}")
        sys.exit(1)
    else:
        print(f"CI SYNC GATE PASSED: {len(disk_db)} markdown files verified in sync, 0 numbering holes, 0 broken links.")
        sys.exit(0)
